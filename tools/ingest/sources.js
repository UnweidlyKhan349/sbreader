#!/usr/bin/env node
/* Writes tools/ingest/sources.json: every tournament (from data/meta.json)
   and, in bank order, its packets: the round label, round number and the
   link the questions were taken from. It's the list of what to fetch, and
   the skeleton the bank is rebuilt on.

     node tools/ingest/sources.js

   Run it again after adding a tournament or packet to the bank, before
   node tools/ingest/build.js --write-corrections. */
const path = require('path');
const { ROOT, SOURCES, writeJson, readJson } = require('./lib/common');

function sources() {
  const meta = readJson(path.join(ROOT, 'data', 'meta.json'));
  return {
    note: 'Generated by node tools/ingest/sources.js from data/meta.json and data/bank/.',
    tournaments: meta.tournaments.map((t) => ({
      slug: t.slug,
      name: t.name,
      packets: readJson(path.join(ROOT, 'data', 'bank', t.slug + '.json')).map((p) => {
        const out = {};
        ['rl', 'r', 'u'].forEach((k) => { if (k in p) out[k] = p[k]; });
        out.n = p.q.length;
        return out;
      }),
    })),
  };
}

if (require.main === module) {
  const s = sources();
  // One packet per line, so a change reads as a one-line diff.
  const fs = require('fs');
  const lines = s.tournaments.map((t) => '  {"slug":' + JSON.stringify(t.slug) + ',"name":' + JSON.stringify(t.name) + ',"packets":[\n'
    + t.packets.map((p) => '    ' + JSON.stringify(p)).join(',\n') + ']}');
  fs.writeFileSync(SOURCES, '{"note":' + JSON.stringify(s.note) + ',"tournaments":[\n' + lines.join(',\n') + '\n]}\n');
  const packets = s.tournaments.reduce((n, t) => n + t.packets.length, 0);
  console.log(`Wrote ${s.tournaments.length} tournaments and ${packets} packets to tools/ingest/sources.json.`);
}
module.exports = { sources };
void writeJson;
